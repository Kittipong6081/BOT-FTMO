"""
===============================================================================
holdout_eval.py — Anti-overfit verification (v8.0.10)
===============================================================================
Compares model performance on:
  • Training pool   (data/mr_signal_pool_3000.pkl, seed 42)
  • Holdout pool    (data/mr_signal_pool_holdout.pkl, seed 999)

Both pools generated by `MeanReversionBacktester.generate_episode_signals` but
on different episode-seed grids → independent samples. If the model is healthy
the gap should be small (≤ 5 pp on Pass Rate). A gap > 10 pp signals overfit
to specific episodes the agent memorized.

Usage:
    .venv/bin/python ftmo_trading_bot/scripts/holdout_eval.py \\
        --model models/mr/best/ppo_mr_filter.zip \\
        --vec_normalize models/mr/best/vec_normalize_mr.pkl \\
        --train_pool data/mr_signal_pool_3000.pkl \\
        --holdout_pool data/mr_signal_pool_holdout.pkl
===============================================================================
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import Dict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

os.environ.setdefault("SMC_QUIET", "1")
os.environ.setdefault("BOT_DISABLE_CHRONOS", "1")


def _eval_on_pool(model_path: str, vec_normalize_path: str, pool_path: str,
                  n_episodes: int, ml_threshold: float, risk: float) -> Dict:
    from ml.aux_aware_ppo import AuxAwarePPO
    from stable_baselines3.common.vec_env import DummyVecEnv, VecNormalize
    from ml.mean_reversion_env import MeanReversionFilterEnv

    def _make_env():
        return MeanReversionFilterEnv(
            data_dir=os.path.join(ROOT, "data", "ohlcv"),
            enable_risk_penalty=True,
            signal_pool_path=pool_path,
            outcome_noise_std=0.0,
            ml_filter_threshold=ml_threshold,
            risk_per_trade=risk,
            verbose=False,
        )

    raw_env = DummyVecEnv([_make_env])
    if vec_normalize_path and os.path.exists(vec_normalize_path):
        env = VecNormalize.load(vec_normalize_path, raw_env)
        env.training = False
        env.norm_reward = False
    else:
        env = raw_env

    model = AuxAwarePPO.load(model_path)

    passes = 0
    breaches = 0
    profits = []
    win_rates = []
    take_rates = []
    dds_total = []
    dds_daily = []
    trades_per_ep = []

    for ep in range(n_episodes):
        obs = env.reset()
        done = False
        last_info: Dict = {}
        while not done:
            action, _ = model.predict(obs, deterministic=True)
            obs, _r, dones, infos = env.step(action)
            done = dones[0]
            last_info = infos[0] if infos else {}
        s = last_info.get("episode_summary", {})
        if s.get("passed", False):
            passes += 1
        if s.get("breached", False):
            breaches += 1
        profits.append(s.get("profit", 0.0))
        win_rates.append(s.get("win_rate", 0.0))
        take_rates.append(s.get("take_rate", 0.0))
        dds_total.append(s.get("total_dd_pct", 0.0))
        dds_daily.append(s.get("max_daily_dd_pct", 0.0))
        trades_per_ep.append(s.get("total_takes", 0))

    return {
        "n": n_episodes,
        "pass_rate": passes / n_episodes,
        "breach_rate": breaches / n_episodes,
        "win_rate": float(np.mean(win_rates)),
        "take_rate": float(np.mean(take_rates)),
        "total_dd_max": float(np.max(dds_total)),
        "daily_dd_max": float(np.max(dds_daily)),
        "profit_avg": float(np.mean(profits)),
        "trades_avg": float(np.mean(trades_per_ep)),
    }


def _print_metrics(label: str, m: Dict):
    print(f"\n  📊 {label}  (n={m['n']})")
    print(f"     Pass Rate         : {m['pass_rate']*100:6.2f}%")
    print(f"     Breach Rate       : {m['breach_rate']*100:6.2f}%")
    print(f"     Win Rate (avg)    : {m['win_rate']*100:6.2f}%")
    print(f"     Take Rate (avg)   : {m['take_rate']*100:6.2f}%")
    print(f"     Total DD max      : {m['total_dd_max']*100:6.2f}%")
    print(f"     Daily DD max      : {m['daily_dd_max']*100:6.2f}%")
    print(f"     Profit avg        : ${m['profit_avg']:>+8,.2f}")
    print(f"     Trades avg/ep     : {m['trades_avg']:6.1f}")


def main():
    parser = argparse.ArgumentParser(description="Anti-overfit holdout eval")
    parser.add_argument("--model", default=os.path.join(ROOT, "models/mr/best/ppo_mr_filter.zip"))
    parser.add_argument("--vec_normalize", default=os.path.join(ROOT, "models/mr/best/vec_normalize_mr.pkl"))
    parser.add_argument("--train_pool", default=os.path.join(ROOT, "data/mr_signal_pool_3000.pkl"))
    parser.add_argument("--holdout_pool", default=os.path.join(ROOT, "data/mr_signal_pool_holdout.pkl"))
    parser.add_argument("--n_episodes", type=int, default=2000)
    parser.add_argument("--ml_threshold", type=float, default=0.30)
    parser.add_argument("--risk_per_trade", type=float, default=0.0085)  # v8.0.43c sync
    args = parser.parse_args()

    if not os.path.exists(args.model):
        print(f"❌ Model not found: {args.model}")
        sys.exit(1)
    if not os.path.exists(args.train_pool):
        print(f"❌ Train pool not found: {args.train_pool}")
        sys.exit(1)
    if not os.path.exists(args.holdout_pool):
        print(f"❌ Holdout pool not found: {args.holdout_pool}")
        print(f"   Build it: python scripts/build_mr_signal_pool.py --pool_size 800 --seed 999 \\")
        print(f"             --save_path {args.holdout_pool}")
        sys.exit(1)

    print("=" * 72)
    print(" 🔬 Anti-Overfit Holdout Eval (v8.0.10)")
    print("=" * 72)
    print(f"   Model:        {os.path.basename(args.model)}")
    print(f"   Train pool:   {os.path.basename(args.train_pool)}")
    print(f"   Holdout pool: {os.path.basename(args.holdout_pool)}")
    print(f"   Episodes per pool: {args.n_episodes}")
    print("=" * 72)

    train = _eval_on_pool(
        args.model, args.vec_normalize, args.train_pool,
        args.n_episodes, args.ml_threshold, args.risk_per_trade,
    )
    _print_metrics("Train pool (seen during training)", train)

    holdout = _eval_on_pool(
        args.model, args.vec_normalize, args.holdout_pool,
        args.n_episodes, args.ml_threshold, args.risk_per_trade,
    )
    _print_metrics("Holdout pool (NEVER seen during training)", holdout)

    # Compute overfit gap
    print("\n" + "=" * 72)
    print(" 🎯 Overfit Diagnosis")
    print("=" * 72)
    delta_pass = (train["pass_rate"] - holdout["pass_rate"]) * 100
    delta_win = (train["win_rate"] - holdout["win_rate"]) * 100
    delta_profit = train["profit_avg"] - holdout["profit_avg"]

    print(f"   Δ Pass Rate         : {delta_pass:+6.2f} pp  (train − holdout)")
    print(f"   Δ Win Rate          : {delta_win:+6.2f} pp")
    print(f"   Δ Profit avg        : ${delta_profit:+8,.2f}")
    print()

    if abs(delta_pass) <= 5.0:
        verdict = "✅ HEALTHY — model generalizes well (gap ≤ 5 pp)"
    elif abs(delta_pass) <= 10.0:
        verdict = "🟡 MILD OVERFIT — gap 5-10 pp, acceptable but watch"
    else:
        verdict = "❌ OVERFIT — gap > 10 pp, model memorized training pool"

    print(f"   Verdict: {verdict}")
    print("=" * 72)

    if abs(delta_pass) > 10.0:
        sys.exit(1)


if __name__ == "__main__":
    main()
